const golden = JSON.parse(readFileSync(new URL('./fixtures/golden.json', import.meta.url)));
const mod = Object.fromEntries(PROVIDERS.map((p) => [p.id, p]));

/** A fake fetch (browser-style) answering from a scenario handler; records every request. */
function fakeFetch(handler) {
  const calls = [];
  const f = async (url, init = {}) => {
    const method = (init.method || 'GET').toUpperCase();
    calls.push(`${method} ${url}${init.body ? ' ' + init.body : ''}`);
    const r = handler(method, String(url), init.body);
    if (!r) return new Response('not found', { status: 404 });
    return new Response(r.body, { status: r.status, headers: { 'content-type': r.type } });
  };
  f.calls = calls;
  return f;
}
const netFor = (f) => createNet(() => ({ edge: false }), f); // direct mode, so parity compares the exact upstream URLs

// ---- Equivalence with the ORIGINAL CloudStream scrapers (golden.json is generated by scripts/make-golden.mjs) ----
for (const sc of scenarios) {
  test(`parity with original scraper: ${sc.id}`, async () => {
    const f = fakeFetch(sc.handler);
    const p = mod[sc.scraper];
    const ctx = makeCtx(netFor(f), p);
    // compat:true = original file-extension rules, so output must be IDENTICAL to the extension's
    const streams = await p.search(sc.meta, ctx, { compat: true, DOMParser });
    const g = golden[sc.id];
    assert.deepEqual(streams.map((s) => ({ url: s.url, quality: s.quality })), g.streams.map((s) => ({ url: s.url, quality: s.quality })), 'streams (url, quality, order)');
    assert.deepEqual([...f.calls].sort(), g.requests, 'exact same network requests (the port makes no extra TMDB call)');
  });
}

test('deliberate deviation: .mov/.m4v/.webm are accepted unless compat mode is on', async () => {
  const sc = scenarios.find((s) => s.id === 'df-movie-variant2');
  const std = await resolveStreams(sc.meta, { net: netFor(fakeFetch(sc.handler)), enabled: { 'bdix-cf': false, 'bdix-fh': false } });
  const compat = await resolveStreams(sc.meta, { net: netFor(fakeFetch(sc.handler)), enabled: { 'bdix-cf': false, 'bdix-fh': false }, compat: true });
  const movs = std.streams.filter((s) => s.container === 'mov');
  assert.equal(movs.length, 1); assert.match(movs[0].url, /720p\.WEB-DL\.MOV$/);
  assert.equal(compat.streams.filter((s) => s.container === 'mov').length, 0);
  assert.equal(std.streams.length, compat.streams.length + 1);
});

