test('failure classification: unreachable vs http error vs empty vs ok', async () => {
  const sc = scenarios.find((s) => s.id === 'df-movie-variant2');
  const only = { 'bdix-cf': false, 'bdix-fh': false };
  const down = async () => { throw new TypeError('Failed to fetch'); };
  assert.equal((await resolveStreams(sc.meta, { net: netFor(down), enabled: only })).status['bdix-df'].state, 'unreachable');
  const r500 = await resolveStreams(scenarios.find((s) => s.id === 'df-all-fail').meta, { net: netFor(fakeFetch(scenarios.find((s) => s.id === 'df-all-fail').handler)), enabled: only });
  assert.equal(r500.status['bdix-df'].state, 'error');
  const empty = await resolveStreams(sc.meta, { net: netFor(fakeFetch(() => ({ status: 200, body: '{"search":[]}', type: 'application/json' }))), enabled: only });
  assert.equal(empty.status['bdix-df'].state, 'empty');
  const ok = await resolveStreams(sc.meta, { net: netFor(fakeFetch(sc.handler)), enabled: only });
  assert.equal(ok.status['bdix-df'].state, 'ok'); assert.ok(ok.streams.length > 0);
  assert.equal(classify({ attempts: 0, network: 0, http: 0 }, 0), 'empty');
});

test('one provider failing/timing out does not affect the others; disabled providers are never called', async () => {
  const df = scenarios.find((s) => s.id === 'df-movie-variant2');
  const f = fakeFetch((m, url, body) => (url.includes('15.1.1.50') || url.includes('circleftp') ? null : df.handler(m, url, body)));
  const hang = (url, init) => (String(url).includes('flixhub') ? new Promise((_, rej) => init.signal.addEventListener('abort', () => rej(init.signal.reason))) : f(url, init));
  const progress = [];
  const r = await resolveStreams(df.meta, { net: netFor(hang), timeoutMs: 80, onProgress: (id, ev) => progress.push(`${id}:${ev}`) });
  assert.equal(r.status['bdix-fh'].state, 'timeout');
  assert.equal(r.status['bdix-df'].state, 'ok');
  assert.ok(progress.includes('bdix-fh:done') && progress.includes('bdix-df:start'));
  const g = fakeFetch(df.handler);
  await resolveStreams(df.meta, { net: netFor(g), enabled: Object.fromEntries(PROVIDERS.map((p) => [p.id, false])) });
  assert.equal(g.calls.length, 0, 'nothing is requested when all providers are disabled');
});

