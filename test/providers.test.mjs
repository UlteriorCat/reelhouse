test('net: gateway envelope, edge proxy, direct, mediaUrl', async () => {
  const seen = [];
  const f = async (url, init) => { seen.push({ url: String(url), init }); return new Response('{}'); };
  const gw = createNet(() => ({ gatewayUrl: 'http://127.0.0.1:8787/', gatewayToken: 't k' }), f);
  await gw.request('http://172.16.50.12/DHAKA-FLIX-12/', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{"a":1}' });
  assert.equal(seen[0].url, 'http://127.0.0.1:8787/p?k=t%20k'); assert.equal(seen[0].init.headers['Content-Type'], 'text/plain', 'simple request: no preflight');
  assert.deepEqual(JSON.parse(seen[0].init.body), { url: 'http://172.16.50.12/DHAKA-FLIX-12/', method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{"a":1}' });
  assert.match(gw.mediaUrl({ url: 'http://x/a b.mkv', headers: {} }, { download: true, filename: 'a b.mkv' }), /^http:\/\/127\.0\.0\.1:8787\/s\?u=http%3A%2F%2Fx%2Fa\+b\.mkv&k=t\+k&dl=1&n=a\+b\.mkv$/);

  seen.length = 0;
  const direct = createNet(() => ({}), f, { edgeBase: 'https://site.test' });
  await direct.request('http://172.16.50.12/x', { provider: { edge: false } });
  assert.equal(seen[0].url, 'http://172.16.50.12/x'); assert.equal(seen[0].init.referrerPolicy, 'no-referrer'); assert.equal(seen[0].init.credentials, 'omit');
  await direct.request('https://flixhub.net/watch/movie/x', { provider: { edge: true } });
  assert.equal(seen[1].url, 'https://site.test/api/proxy?u=https%3A%2F%2Fflixhub.net%2Fwatch%2Fmovie%2Fx');
  assert.equal(direct.mediaUrl({ url: 'http://a/b.mp4' }), 'http://a/b.mp4');
  await assert.rejects(createNet(() => ({}), async () => { throw new TypeError('x'); }).request('http://a'), (e) => e instanceof NetError && e.kind === 'network');
});

test('net.diagnose: ok / cors-blocked / unreachable', async () => {
  const mk = (corsFails, anyFails) => createNet(() => ({}), async (u, init = {}) => { if (init.mode === 'no-cors' ? anyFails : corsFails) throw new TypeError('x'); return new Response(''); });
  assert.equal(await mk(false, false).diagnose('http://a'), 'ok');
  assert.equal(await mk(true, false).diagnose('http://a'), 'cors');
  assert.equal(await mk(true, true).diagnose('http://a'), 'unreachable');
  const gw = (status) => createNet(() => ({ gatewayUrl: 'http://g' }), async () => new Response('', { status }));
  assert.deepEqual([await gw(200).diagnose('http://a'), await gw(401).diagnose('http://a'), await gw(403).diagnose('http://a'), await gw(502).diagnose('http://a')], ['ok', 'auth', 'blocked', 'unreachable']);
});

test('duplicate URLs from different providers keep the entry that knows the resolution (order-independent)', async () => {
  const same = 'http://x.invalid/m/same.mp4';
  const respond = (url) => {
    if (url.startsWith('http://new.circleftp.net:5000/api/posts?')) return { status: 200, body: JSON.stringify({ posts: [{ id: 1, type: 'singleVideo', title: 'The Matrix (1999) 1080p', name: 'The Matrix' }] }) };
    if (url.endsWith('/api/posts/1')) return { status: 200, body: JSON.stringify({ post: { content: same, title: 'The Matrix (1999) 1080p' } }) };
    if (url === 'https://flixhub.net/watch/movie/the-matrix') return { status: 200, body: `<video id="theaterPlayer" data-stream-url="${same}"></video>` };
    return { status: 404, body: 'nf' };
  };
  for (const slow of ['circleftp', 'flixhub']) {
    const f = async (url) => {
      if (String(url).includes(slow)) await new Promise((r) => setTimeout(r, 40)); // force this provider to finish last
      const r = respond(String(url));
      return new Response(r.body, { status: r.status });
    };
    const r = await resolveStreams({ type: 'movie', title: 'The Matrix', year: '1999' }, { net: createNet(() => ({ edge: false }), f), enabled: { 'bdix-df': false }, DOMParser });
    assert.equal(r.status['bdix-cf'].count, 1); assert.equal(r.status['bdix-fh'].count, 1, 'both providers found it');
    assert.equal(r.streams.length, 1, 'one ticket for one file');
    assert.equal(r.streams[0].quality, '1080p', `kept the entry with a known resolution when ${slow} finished last`);
  }
});

test('settle window: playback is not held up by a slow provider once another has streams', async () => {
  const df = scenarios.find((x) => x.id === 'df-movie-variant2');
  const aborted = [];
  const f = (url, init = {}) => {
    if (String(url).includes('flixhub')) return new Promise((_, rej) => init.signal.addEventListener('abort', () => { aborted.push('fh'); rej(init.signal.reason); }));
    const r = df.handler(init.method || 'GET', String(url), init.body);
    return Promise.resolve(r ? new Response(r.body, { status: r.status }) : new Response('nf', { status: 404 }));
  };
  const t0 = Date.now();
  const r = await resolveStreams(df.meta, { net: createNet(() => ({ edge: false }), f), settleMs: 120, timeoutMs: 10000, DOMParser });
  assert.ok(Date.now() - t0 < 1500, 'returned long before the 10s timeout');
  assert.equal(r.partial, true); assert.equal(r.status['bdix-fh'].state, 'slow'); assert.equal(r.status['bdix-df'].state, 'ok');
  assert.ok(r.streams.length >= 3);
  await new Promise((x) => setTimeout(x, 30)); assert.deepEqual(aborted, ['fh', 'fh'], 'both parallel FlixHub requests (slug and slug-1) were aborted, not leaked');
  // no settle window (download sheet): waits for everyone
  const full = await resolveStreams(df.meta, { net: createNet(() => ({ edge: false }), (u, i) => (String(u).includes('flixhub') ? Promise.resolve(new Response('nf', { status: 404 })) : f(u, i))), DOMParser });
  assert.equal(full.partial, false);
});
